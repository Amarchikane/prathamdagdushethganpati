function transliterate(mrStr) {
  // Tokenize and match
  return mrStr.split(/([ ()\/,.-]+)/).map(token => {
    if (marathiToLatinMap[token]) return marathiToLatinMap[token];
    return token;
  }).join('');
}

function getLandmark(nameStr) {
  if (nameStr.includes("शाहू चौक")) return { mr: "शाहू चौक", en: "Shahu Chowk" };
  if (nameStr.includes("बाजीराव रोड")) return { mr: "बाजीराव रोड", en: "Bajirao Road" };
  if (nameStr.includes("मंडई")) return { mr: "मंडई", en: "Mandai" };
  if (nameStr.includes("सरस्वती मंदिर")) return { mr: "सरस्वती मंदिर", en: "Saraswati Mandir" };
  if (nameStr.includes("केळकर संग्रहालय")) return { mr: "केळकर संग्रहालय", en: "Kelkar Museum" };
  if (nameStr.includes("बदामी हौद")) return { mr: "बदामी हौद", en: "Badami Haud" };
  if (nameStr.includes("महाराणा प्रताप")) return { mr: "महाराणा प्रताप", en: "Maharana Pratap" };
  if (nameStr.includes("अकरा मारुती")) return { mr: "अकरा मारुती चौक", en: "Akara Maruti Chowk" };
  return { mr: "शुक्रवार पेठ", en: "Shukrawar Peth" };
}

let allDonors = [];
let idCounter = 1;

pagesData.forEach(p => {
  p.sections.forEach(sec => {
    sec.names.forEach(name => {
      const cleanName = name.trim();
      const lm = getLandmark(cleanName);
      const enName = transliterate(cleanName);
      
      // Generate phonetic aliases
      const wordsMr = cleanName.replace(/[(),.\/-]/g, ' ').split(/\s+/).filter(Boolean);
      const wordsEn = enName.replace(/[(),.\/-]/g, ' ').split(/\s+/).filter(Boolean);
      const aliases = Array.from(new Set([
        ...wordsMr,
        ...wordsEn.map(w => w.toLowerCase())
      ]));

      allDonors.push({
        id: `REG-${String(idCounter).padStart(3, '0')}`,
        name_mr: cleanName,
        name_en: enName,
        phonetic_aliases: aliases,
        amount: sec.amount,
        year: 2024,
        landmark_mr: lm.mr,
        landmark_en: lm.en,
        book_ref: p.page,
        note_mr: sec.note || "",
        note_en: sec.note ? "Handwritten Entry" : ""
      });

      idCounter++;
    });
  });
});

